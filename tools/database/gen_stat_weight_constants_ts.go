package database

import (
	"fmt"
	"os"

	"github.com/wowsims/forever/sim/core"
)

const statWeightConstantsTSOutputPath = "ui/sim/wasm/stat_weights_constants_auto_gen.ts"

// Mirrors the stat weight Target ± constants into the UI, so the EP ± and the stat sweep's Target ± use
// the sim's numbers.
func GenerateStatWeightConstantsTSFile() error {
	content := fmt.Sprintf(`// Code generated by tools/database/gen_stat_weight_constants_ts.go. DO NOT EDIT.

export const STAT_WEIGHT_Z90 = %v;

export const STAT_WEIGHT_MAX_TOP_UP_PASSES = %v;

export const STAT_WEIGHT_TARGET_PROBE_ITERATIONS = %v;
`, core.StatWeightZ90, core.StatWeightMaxTopUpPasses, core.StatWeightTargetProbeIterations)

	if err := os.WriteFile(statWeightConstantsTSOutputPath, []byte(content), 0644); err != nil {
		return fmt.Errorf("failed to write generated stat weight constants TS file: %w", err)
	}
	return nil
}
