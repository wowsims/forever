package database

import (
	"fmt"
	"go/format"
	"maps"
	"os"
	"reflect"
	"slices"
	"strconv"
	"strings"

	"github.com/wowsims/forever/sim/core/proto"
)

const itemEffectsTableFileName = "sim/common/forever/item_effects_auto_gen.go"

// The effects the item and enchant helpers in sim/common/shared resolve a registration from: on-use
// cooldowns and categories, stats scaled to every item level state, proc rates and stacking auras.
// The sim reads them from this file and not from the database.
func GenerateItemEffectsTable(itemEffects map[int32][]*proto.ItemEffect, enchantEffects map[int32][]*proto.ItemEffect) error {
	var b strings.Builder
	b.WriteString("// Code generated by tools/database/gen_db. DO NOT EDIT.\n\n")
	b.WriteString("package forever\n\n")
	b.WriteString("import (\n\"github.com/wowsims/forever/sim/common/shared\"\n\"github.com/wowsims/forever/sim/core/proto\"\n)\n\n")
	b.WriteString("func init() {\n")
	writeEffectsTable(&b, "shared.RegisterItemEffects", itemEffects)
	writeEffectsTable(&b, "shared.RegisterEnchantEffects", enchantEffects)
	b.WriteString("}\n")

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("the generated item effects table does not parse, refusing to write it: %w", err)
	}

	if err := os.WriteFile(itemEffectsTableFileName, out, 0644); err != nil {
		return fmt.Errorf("failed to write file %s: %w", itemEffectsTableFileName, err)
	}

	return nil
}

// One ID per entry, in ID order, with one effect per line under it.
func writeEffectsTable(b *strings.Builder, register string, table map[int32][]*proto.ItemEffect) {
	fmt.Fprintf(b, "%s(map[int32][]*proto.ItemEffect{\n", register)
	for _, id := range slices.Sorted(maps.Keys(table)) {
		fmt.Fprintf(b, "%d: {\n", id)
		for _, effect := range table[id] {
			fmt.Fprintf(b, "%s,\n", protoLiteral(reflect.ValueOf(effect), true))
		}
		b.WriteString("},\n")
	}
	b.WriteString("})\n")
}

// A proto message as a Go composite literal, with the type left out where Go allows it. A scalar
// field at its zero value is left out, but a set oneof case and a present message are written even
// when empty: proto.Equal tells either apart from an absent one.
func protoLiteral(v reflect.Value, elideType bool) string {
	switch v.Kind() {
	case reflect.Pointer:
		fields := protoFields(v.Elem())
		if elideType {
			return "{" + fields + "}"
		}
		return "&" + v.Type().Elem().String() + "{" + fields + "}"
	case reflect.Interface:
		return protoLiteral(v.Elem(), false)
	case reflect.Map:
		keys := v.MapKeys()
		slices.SortFunc(keys, func(a, b reflect.Value) int { return int(a.Int() - b.Int()) })
		elems := make([]string, len(keys))
		for i, key := range keys {
			elems[i] = fmt.Sprintf("%d: %s", key.Int(), protoLiteral(v.MapIndex(key), true))
		}
		return v.Type().String() + "{" + strings.Join(elems, ", ") + "}"
	case reflect.String:
		return strconv.Quote(v.String())
	case reflect.Float64:
		return num(v.Float())
	case reflect.Bool:
		return strconv.FormatBool(v.Bool())
	case reflect.Int32:
		return strconv.FormatInt(v.Int(), 10)
	}

	panic(fmt.Sprintf("the item effects table has no literal for a %s", v.Type()))
}

// The fields a message sets, as "Name: value", in declaration order.
func protoFields(v reflect.Value) string {
	var parts []string
	for i := 0; i < v.NumField(); i++ {
		field, value := v.Type().Field(i), v.Field(i)
		_, isField := field.Tag.Lookup("protobuf")
		_, isOneof := field.Tag.Lookup("protobuf_oneof")
		if (!isField && !isOneof) || value.IsZero() || (value.Kind() == reflect.Map && value.Len() == 0) {
			continue
		}
		parts = append(parts, field.Name+": "+protoLiteral(value, false))
	}
	return strings.Join(parts, ", ")
}

// The effects of every item or enchant registered by hand, and of every one a generated file writes a
// registration for, live or commented out, so that uncommenting one finds its data. A skipped effect
// names no helper.
func registeredEffects(effects map[int32][]*proto.ItemEffect, byHand func(int32) bool, groupSets ...[]*Group) map[int32][]*proto.ItemEffect {
	registered := map[int32][]*proto.ItemEffect{}
	for id, idEffects := range effects {
		if len(idEffects) > 0 && byHand(id) {
			registered[id] = idEffects
		}
	}
	for _, groups := range groupSets {
		for _, grp := range groups {
			for _, entry := range grp.Entries {
				if entry.Skipped {
					continue
				}
				for _, variant := range entry.Variants {
					if id := int32(variant.ID); len(effects[id]) > 0 {
						registered[id] = effects[id]
					}
				}
			}
		}
	}
	return registered
}
