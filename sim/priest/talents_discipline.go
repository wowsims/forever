// Your non-periodic critical heals create a protective shield on the target, absorbing X% of the amount healed.
// Shields up to 20 damage per level and lasts 12 sec.
func (priest *Priest) applyDivineAegis() {
	if priest.Talents.DivineAegis == 0 {
		return
	}

	shieldFraction := spellData.DivineAegis.EffectAt(1).FractionAt(priest.Talents.DivineAegis)
	// The tooltip prices the cap as $s2*$pl, the second effect's points per caster level.
	maxShield := spellData.DivineAegis.EffectAt(2).ValueAt(priest.Talents.DivineAegis) * float64(priest.Level)
	shields := priest.NewAllyDamageAbsorptionAuraArray(func(target *core.Unit) *core.DamageAbsorptionAura {
		return target.NewDamageAbsorptionAura(core.AbsorptionAuraConfig{
			Aura: core.Aura{
				Label:    "Divine Aegis - " + priest.Label,
				ActionID: core.ActionID{SpellID: spellData.DivineAegis.Highest().ID},
				Duration: core.DurationFromSeconds(12),
			},
			ShieldStrengthCalculator: func(_ *core.Unit) float64 { return 0 },
		})
	})
	aegisSpells := make(map[*core.Spell]*core.Spell)
	var pendingStrength float64
	priest.OnSpellRegistered(func(sourceSpell *core.Spell) {
		if !sourceSpell.ProcMask.Matches(core.ProcMaskSpellHealing) {
			return
		}
		// A heal whose row only heals over time or rules out crits, or whose id the store does not carry,
		// never lands a direct critical heal. A spell with no spell id is an item's, and keeps its proc.
		row := spelldata.Find(sourceSpell.ActionID.SpellID)
		if sourceSpell.ActionID.SpellID != 0 && (row == spelldata.Nil || row.ProcHealEffect().Aura == dbcenums.A_PERIODIC_HEAL || row.CannotCrit()) {
			return
		}

		config := spelldata.SpellConfig(
			&priest.Unit,
			spellData.DivineAegisTriggered.Highest(),
			spelldata.Magic(core.ProcMaskEmpty),
			spelldata.RemoveFlags(core.SpellFlagAPL),
			spelldata.Flags(core.SpellFlagNoOnCastComplete),
		)
		sourceTag := sourceSpell.ActionID.SpellID
		if sourceTag == 0 && sourceSpell.ActionID.ItemID != 0 {
			sourceTag = -sourceSpell.ActionID.ItemID
		}
		config.ActionID.Tag = sourceTag
		config.SourceActionID = sourceSpell.ActionID
		config.ApplyEffects = func(sim *core.Simulation, target *core.Unit, spell *core.Spell) {
			shield := shields.Get(target)
			if shield.IsActive() {
				shield.Aura.Activate(sim)
			} else {
				shield.Activate(sim)
			}
			previousStrength := shield.ShieldStrength
			shield.ShieldStrength = min(previousStrength+pendingStrength, maxShield)
			gained := shield.ShieldStrength - previousStrength
			shield.SetStacks(sim, max(1, int32(shield.ShieldStrength)))
			spell.RecordShielding(target, gained)
			spell.SpellMetrics[target.UnitIndex].Hits++
			if gained > 0 {
				sourceSpell.RecordCustomMetric(target, "divine_aegis", gained)
			}
		}
		aegisSpells[sourceSpell] = priest.RegisterSpell(config)
	})
	priest.MakeProcTriggerAura(core.ProcTrigger{
		Name:             "Divine Aegis",
		Callback:         core.CallbackOnHealDealt,
		CanProcFromProcs: spellData.DivineAegis.Highest().CanProcFromProcs(),
		Handler: func(sim *core.Simulation, spell *core.Spell, result *core.SpellResult) {
			if !result.DidCrit() {
				return
			}
			aegisSpell := aegisSpells[spell]
			if aegisSpell == nil {
				return
			}
			pendingStrength = result.Damage * shieldFraction
			aegisSpell.Proc(sim, result.Target)
		},
	})
}

// Infuses the target with power, increasing their spell damage and healing done by 20% for 15 sec.
func (priest *Priest) applyPowerInfusion() {
	if !priest.Talents.PowerInfusion {
		return
	}

	piAura := buffs.NewSpellDataPowerInfusionsAura(&priest.Unit, true, 0)

	config := spelldata.SpellConfig(&priest.Unit, spellData.PowerInfusion.Highest(), spelldata.Flags(core.SpellFlagAPL))
	config.ApplyEffects = func(sim *core.Simulation, _ *core.Unit, _ *core.Spell) {
		piAura.Activate(sim)
	}
	piSpell := priest.RegisterSpell(config)

	priest.AddMajorCooldown(core.MajorCooldown{
		Spell: piSpell,
		Type:  core.CooldownTypeDPS,
	})
}
