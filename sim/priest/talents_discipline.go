func (priest *Priest) registerDisciplineTalents() {
	// Tier 1
	priest.applyPowerInLight()
	priest.applyWandSpecialization()
	priest.applyTwinDisciplines()

	// Tier 2
	priest.applySilentResolve()
	priest.applyHolyPrecision()
	priest.applyImprovedPowerWordShield()
	priest.applyMartyrdom()

	// Tier 3
	priest.applyMentalAgility()
	priest.applyInnerFocus()
	priest.applyMeditation()

	// Tier 4
	priest.applyImprovedInnerFire()
	priest.applyMentalStrength()
	priest.applySoulWarding()
	priest.applyImprovedManaBurn()

	// Tier 5
	priest.applyPenance()

	// Tier 6
	priest.applyDivineAegis()

	// Tier 7
	priest.applyPowerInfusion()
}

// Your Smite and Penance spells deal X% increased damage to targets afflicted with your Holy Fire or Shadow Word: Pain.
// The marker on each target is up while any rank of this priest's Holy Fire or Shadow Word: Pain is on it
// (attachPowerInLightMarker).
func (priest *Priest) applyPowerInLight() {
	if priest.Talents.PowerInLight == 0 {
		return
	}

	multiplier := spellData.PowerInLight.MultiplierAt(priest.Talents.PowerInLight)
	priest.powerInLightAuras = priest.NewEnemyAuraArray(func(target *core.Unit) *core.Aura {
		return target.GetOrRegisterAura(core.Aura{
			Label:    "Power in Light - " + priest.Label,
			Duration: core.NeverExpires,
		}).AttachDDBC(1, 2, &priest.AttackTables, func(_ *core.Simulation, spell *core.Spell, _ *core.AttackTable) float64 {
			if spell.Matches(PriestSpellSmite | PriestSpellPenance) {
				return multiplier
			}
			return 1
		})
	})
}

// Switches the target's Power in Light marker from a Holy Fire or Shadow Word: Pain rank's dot. A dot
// that drops leaves the marker on while another of them is still up; a replaced rank's dot expires
// before the new rank's dot gains, so the marker ends up on.
func (priest *Priest) attachPowerInLightMarker(config *core.SpellConfig) {
	if priest.powerInLightAuras == nil {
		return
	}

	config.Dot.Aura.OnGain = func(aura *core.Aura, sim *core.Simulation) {
		priest.powerInLightAuras.Get(aura.Unit).Activate(sim)
	}
	// The dropping dot already reads inactive here.
	config.Dot.Aura.OnExpire = func(aura *core.Aura, sim *core.Simulation) {
		for _, spell := range priest.Spellbook {
			if spell.Matches(PriestSpellHolyFire|PriestSpellShadowWordPain) && spell.Dot(aura.Unit).IsActive() {
				return
			}
		}
		priest.powerInLightAuras.Get(aura.Unit).Deactivate(sim)
	}
}

// Wand damage, +13% / +25%: the wand's shots are the priest's only ranged autos. The row's school mask
// (126) leaves out physical wands.
func (priest *Priest) applyWandSpecialization() {
	if priest.Talents.WandSpecialization == 0 {
		return
	}

	const schools = 126
	priest.AddStaticMod(core.SpellModConfig{
		Kind:       core.SpellMod_DamageDone_Pct,
		ProcMask:   core.ProcMaskRangedAuto,
		School:     core.SpellSchool(schools),
		FloatValue: spellData.WandSpecialization.Effect(dbcenums.A_MOD_DAMAGE_PERCENT_DONE, schools).FractionAt(priest.Talents.WandSpecialization),
	})
}

